async (page) => {
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors = [], details = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = { startedAt: Date.now(), upstreamModel: 'demo', platform: 'trae', region: 'cn', account: '模拟账号', status: 'success', httpStatus: 200, errorCode: null, durationMs: 2000, stream: true, attempts: 1, inputTokens: 100, outputTokens: 20, totalTokens: 120, credits: null };
  const records = [{ id: 'new', model: 'new-dialog', hasConversation: true }, { id: 'old', model: 'old-dialog' }].map(row => ({ ...base, ...row }));
  const conversation = { request: [{ role: 'system', content: '系统规则' }, { role: 'user', content: '测试问题\n<img src=x onerror="window.__conversationXss=true">' }], response: [{ role: 'assistant', index: 0, content: '模型回复\n第二行内容', reasoning: '模拟分析', tools: [{ name: 'lookup', arguments: '{"id":1}' }] }], truncated: true, complete: false };
  await page.context().route('**/api/gateway/usage', route => route.fulfill({ json: { records, limit: 2000, warning: '' } }));
  await page.context().route('**/api/gateway/usage/*', route => { details.push(route.request().url()); return route.fulfill({ json: { record: records[0], conversation, warning: '' } }); });
  await page.goto('http://127.0.0.1:18887/admin/gateway?tab=usage#theme=default');
  const panel = page.locator('.usage-panel');
  const open = model => panel.getByRole('row').filter({ hasText: model }).getByRole('button', { name: '详情', exact: true }).click();
  await open('old-dialog');
  await page.getByRole('tab', { name: '对话内容', exact: true }).click();
  await page.getByText('此历史记录未保存对话原文，无法恢复。新调用会在此展示请求消息和模型回复。', { exact: true }).waitFor();
  assert(details.length === 0, 'Legacy records should explain missing text without making a request');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await open('new-dialog');
  const content = page.getByRole('region', { name: '对话内容' });
  await content.getByText('模型回复\n第二行内容', { exact: true }).waitFor();
  await content.getByText('系统规则', { exact: true }).waitFor();
  await content.getByText('工具调用 · lookup', { exact: true }).waitFor();
  assert(await content.innerText().then(text => text.includes('仅保留部分内容') && text.includes('下方回复可能不完整')), 'Explain truncation and partial replies');
  assert(await content.locator('img').count() === 0 && !await page.evaluate(() => window.__conversationXss), 'Render conversation text without executing HTML');
  assert(details.length === 1 && details[0].endsWith('/new'), 'Load only the selected conversation on demand');
  await content.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/playwright/conversation-dark.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '开启可莉主题', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await open('new-dialog');
  await content.getByText('模型回复\n第二行内容', { exact: true }).waitFor();
  await content.scrollIntoViewIfNeeded();
  assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'Conversation must fit mobile screens');
  await page.screenshot({ path: 'output/playwright/conversation-mobile-klee.png', animations: 'disabled' });
  assert(!errors.length, errors.join('; '));
  return 'PASS: on-demand request/reply display, tools, safe text rendering, legacy explanation, truncation/partial markers and mobile theme.';
}
