async (page) => {
  await page.goto('http://127.0.0.1:17865/admin/qoder?tab=models#theme=default');
  await page.setViewportSize({ width: 390, height: 844 });
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const overflow = async label => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), label + ' has horizontal overflow');
  const requests = [];
  page.on('request', req => { if (new URL(req.url()).pathname.startsWith('/api/')) requests.push([req.method(), new URL(req.url()).pathname]); });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.locator('.model-table').getByText('Qoder Auto', { exact: true }).waitFor();
  assert(await page.locator('.model-table .el-table__body-wrapper tbody tr').count() === 3, 'Direct model entry should load without a manual refresh');
  await page.getByRole('textbox', { name: '搜索模型' }).fill('Qoder');
  await page.waitForFunction(() => document.querySelectorAll('.model-table .el-table__body-wrapper tbody tr').length === 1);
  await page.getByRole('button', { name: '用于 API 示例 →', exact: true }).click();
  await page.getByRole('heading', { name: 'API 接入指南' }).waitFor();
  assert((await page.locator('pre').first().innerText()).includes('qoder/Auto'), 'Selected model should be carried to example');
  assert(!page.url().includes('#'), 'Tab navigation should not expose fragment keys');
  await overflow('Mobile API guide');
  await page.getByRole('navigation', { name: '工作空间导航' }).getByRole('button', { name: /账号管理/ }).click();
  await page.getByRole('heading', { name: '已连接账号', exact: false }).waitFor();
  await page.getByRole('textbox', { name: '搜索账号' }).fill('国际版');
  await page.waitForFunction(() => document.querySelectorAll('.account-row').length === 1);
  await page.getByRole('textbox', { name: '搜索账号' }).fill('');
  await page.getByRole('button', { name: '添加账号', exact: true }).click();
  await page.locator('#connect-account[open]').waitFor();
  await overflow('Mobile accounts');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'output/playwright/accounts-dark.png', fullPage: true });
  await page.getByRole('button', { name: '签到中心', exact: true }).click();
  await page.getByRole('heading', { name: 'Qoder 国内开发', exact: true }).waitFor();
  await page.locator('.checkin-row').first().getByText('今日未签到', { exact: true }).waitFor();
  assert((await page.locator('.checkin-row').first().innerText()).includes('今日未签到'), 'Single platform checkin result should match account metadata');
  await page.getByRole('button', { name: '领取奖励', exact: true }).click();
  await page.getByText('签到成功', { exact: true }).waitFor();
  await page.getByRole('button', { name: '额度监控', exact: true }).click();
  await page.getByText('额度包明细（1）', { exact: true }).first().waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await overflow('Mobile quota');
  await page.getByRole('button', { name: '连接设置', exact: true }).click();
  await page.getByRole('heading', { name: 'Qoder API Key', exact: true }).waitFor();
  await overflow('Mobile settings');
  assert(await page.locator('input[type=password]').count() === 1, 'Key must remain masked');
  await page.locator('.platform-switcher').getByRole('link', { name: 'Qoder', exact: true }).click();
  await page.getByRole('heading', { name: '一切就绪，从这里开始。', exact: true }).waitFor();
  assert(new URL(page.url()).hash === '', 'Current platform link must not leave keys in URL');
  await page.locator('.platform-switcher').getByRole('link', { name: 'Trae', exact: true }).click();
  await page.getByRole('heading', { name: '一切就绪，从这里开始。', exact: true }).waitFor();
  assert(new URL(page.url()).port === '17864' && !new URL(page.url()).hash, 'Cross-platform handoff must clear keys');
  await page.getByRole('button', { name: '开启可莉主题', exact: true }).click();
  await page.locator('.platform-switcher').getByRole('link', { name: 'WorkBuddy', exact: true }).click();
  await page.getByRole('button', { name: '可莉主题已开启', exact: true }).waitFor();
  await page.getByRole('heading', { name: '一切就绪，从这里开始。', exact: true }).waitFor();
  await overflow('Mobile WorkBuddy theme');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'output/playwright/workbuddy-klee.png', fullPage: true });
  await page.locator('.brand').click();
  await page.getByRole('heading', { name: /带上嘟嘟可/ }).waitFor();
  await page.screenshot({ path: 'output/playwright/home-klee.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await overflow('Mobile portal theme');
  await page.screenshot({ path: 'output/playwright/home-mobile-klee.png', fullPage: true });
  await page.getByRole('button', { name: '可莉主题已开启', exact: true }).click();
  await overflow('Mobile portal default');
  await page.getByRole('link', { name: '进入工作台', exact: true }).click();
  await page.getByRole('button', { name: '调用统计', exact: true }).click();
  await page.getByRole('heading', { name: '网关用量', exact: true }).waitFor();
  await overflow('Mobile gateway usage');
  assert(errors.length === 0, 'Browser runtime errors: ' + errors.join('; '));
  assert(requests.filter(([method, path]) => method === 'POST' && path === '/api/checkin').length === 1, 'Only the explicitly clicked per-account claim should issue a POST');
  await page.getByRole('button', { name: '工作台', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'output/playwright/gateway-dark.png', fullPage: true });
  return 'PASS: direct models, model selection, account search/onboarding, single claim, quota, settings, platform handoff, Klee persistence, portals, usage and mobile layouts; zero runtime errors.';
}
