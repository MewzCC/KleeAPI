async (page) => {
  page.setDefaultTimeout(5000);
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const uiOrigin = /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\//.test(page.url()) ? new URL(page.url()).origin : 'http://127.0.0.1:18887';
  const errors = [], writes = [];
  await page.emulateMedia({ reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  const longId = 'workbuddy/cn/' + 'long-canonical-model-name-'.repeat(5);
  const models = [
    { id: 'trae/cn/Claude-Sonnet-4', name: 'Claude Sonnet 4', availableAccounts: 2 },
    { id: 'qoder/global/Auto', name: 'Qoder Auto', availableAccounts: 0 },
    { id: longId, name: '较长的真实模型名称用于验证窄屏换行与完整 ID 保留', availableAccounts: 1 },
    ...Array.from({ length: 20 }, (_, index) => ({ id: 'workbuddy/cn/scroll-model-' + index, name: '滚动测试模型 ' + index, availableAccounts: 1 })),
  ];
  let groups = [], failSave = false, failRead = false, warning = '', delayRead = 0;
  const snapshot = () => ({ groups: structuredClone(groups).map(group => ({ ...group, targets: group.targets.map(target => ({ ...target, availableAccounts: 2, lastSuccessAt: Date.now(), errorCode: 'offline_health_fixture' })) })), warning, models });
  await page.context().addInitScript(() => {
    sessionStorage.setItem('klee.gateway', 'klee-offline-auto-models');
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__copiedAutoModel = text; } } });
  });
  await page.context().route('**/*', async route => {
    const req = route.request(), url = new URL(req.url());
    if (!['localhost', '127.0.0.1'].includes(url.hostname)) return route.abort();
    if (!url.pathname.startsWith('/api/') && !url.pathname.startsWith('/v1/')) return route.continue();
    const json = data => route.fulfill({ json: data });
    if (url.pathname === '/api/config') return json({ platform: 'gateway', ports: { gateway: 18887, workbuddy: 18791, trae: 17864, qoder: 17865 }, onboarding: { completed: true, platform: 'gateway' } });
    if (url.pathname === '/api/gateway/status') return json({ accounts: [], models: [...models, ...groups.map(group => ({ id: group.id, name: group.name }))], platforms: [], fetchedAt: Date.now() });
    if (url.pathname.startsWith('/api/gateway/auto-models')) {
      if (req.method() === 'GET') {
        if (delayRead) await new Promise(resolve => setTimeout(resolve, delayRead));
        if (failRead) return route.fulfill({ status: 503, json: { error: { message: '离线模拟：读取失败' } } });
        return json(snapshot());
      }
      if (failSave) return route.fulfill({ status: 500, json: { error: { message: '离线模拟：保存失败，原配置未改变' } } });
      const id = decodeURIComponent(url.pathname.slice('/api/gateway/auto-models/'.length));
      const body = req.method() === 'DELETE' ? undefined : req.postDataJSON();
      writes.push({ method: req.method(), id, body });
      if (req.method() === 'POST') groups.push(body);
      if (req.method() === 'PATCH') groups = groups.map(group => group.id === id ? { ...group, ...body } : group);
      if (req.method() === 'DELETE') groups = groups.filter(group => group.id !== id);
      return route.fulfill({ status: req.method() === 'POST' ? 201 : 200, json: snapshot() });
    }
    if (url.pathname === '/v1/models') return json({ data: models });
    if (url.pathname === '/api/checkin') return json({ accounts: [], fetchedAt: Date.now() });
    return json({});
  });
  await page.setViewportSize({ width: 1440, height: 1000 });
  delayRead = 200;
  await page.goto(uiOrigin + '/admin/gateway?tab=auto-models#theme=default');
  await page.reload();
  await page.getByRole('heading', { name: '先为常用任务建一个组' }).waitFor();
  delayRead = 0;
  await page.getByRole('button', { name: '创建第一个模型组', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '新建模型组', exact: true });
  await dialog.waitFor();
  const modal = page.locator('.auto-model-dialog');
  assert(await page.locator('.auto-intro').count() === 0, 'Intro card is removed');
  assert(await modal.getByRole('button', { name: '保存模型组', exact: true }).isVisible(), 'Save stays visible in the dialog footer');
  const editor = page.getByRole('region', { name: '模型组编辑器', exact: true });
  await editor.waitFor();
  assert(await modal.locator('.auto-catalog article').count() === 10, 'Catalog initially shows only ten models');
  await modal.getByRole('button', { name: '向下滚动查看更多', exact: true }).waitFor();
  await modal.getByRole('button', { name: '向下滚动查看更多', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.auto-model-dialog .el-dialog__body').scrollTop > 0);
  await page.getByRole('textbox', { name: '模型组名称', exact: true }).fill('编程助手');
  await page.getByRole('textbox', { name: '模型组 ID', exact: true }).fill('auto/coding');
  const search = page.getByRole('textbox', { name: '搜索候选模型', exact: true });
  const pickerRow = id => page.locator('.auto-catalog article').filter({ has: page.locator('code', { hasText: id }) });
  await search.fill(models.at(-1).id);
  assert(await modal.locator('.auto-catalog article').count() === 1 && await pickerRow(models.at(-1).id).count() === 1, 'Search includes models beyond the first ten');
  await search.fill('');
  assert(await modal.locator('.auto-catalog article').count() === 10, 'Clearing search restores the default catalog limit');
  await search.fill('Sonnet');
  assert(await page.locator('.auto-catalog article').count() === 1, 'Search filters canonical models');
  await pickerRow(models[0].id).getByRole('button', { name: '添加', exact: true }).click();
  await search.fill('');
  await page.locator('.auto-picker-filters .el-select').click();
  await page.getByRole('option', { name: 'Qoder', exact: true }).click();
  assert(await page.locator('.auto-catalog article').count() === 1, 'Platform filter narrows models');
  await pickerRow(models[1].id).getByRole('button', { name: '添加', exact: true }).click();
  await page.locator('.auto-picker-filters .el-select').click();
  await page.getByRole('option', { name: '全部平台', exact: true }).click();
  await pickerRow(longId).getByRole('button', { name: '添加', exact: true }).click();
  await modal.getByRole('button', { name: /展开全部.*模型/ }).click();
  assert(await modal.locator('.auto-catalog article').count() === models.length, 'Expand reveals the full matching catalog');
  await pickerRow(models.at(-1).id).getByRole('button', { name: '添加', exact: true }).click();
  await modal.getByRole('button', { name: '回到顶部并收起', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.auto-model-dialog .el-dialog__body').scrollTop === 0);
  assert(await modal.locator('.auto-catalog article').count() === 10, 'Collapse restores the ten-row catalog');
  assert(await modal.locator('.auto-target').count() === 4, 'Collapse keeps selected models beyond the first ten');
  await page.getByRole('button', { name: '上移 ' + models[1].id, exact: true }).focus();
  await page.keyboard.press('Enter');
  assert((await page.locator('.auto-target').first().innerText()).includes(models[1].id), 'Keyboard moves candidate priority');
  await page.getByRole('checkbox', { name: '启用候选 ' + models[1].id, exact: true }).focus();
  await page.keyboard.press('Space');
  await page.locator('.auto-advanced summary').click();
  await page.getByText('超时后，上游可能仍在生成。开启超时切换可能产生额外消耗。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '保存模型组', exact: true }).click();
  await page.locator('.auto-group').waitFor();
  assert(groups[0].targets[0].model === models[1].id && groups[0].targets[0].enabled === false, 'Saved order and candidate enabled flags match draft');
  await modal.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '复制 ID', exact: true }).click();
  assert(await page.evaluate(() => window.__copiedAutoModel) === 'auto/coding', 'Copy preserves complete group ID');
  await page.locator('.auto-group').getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByRole('dialog', { name: '编辑模型组', exact: true }).waitFor();
  assert(await page.getByRole('textbox', { name: '模型组 ID', exact: true }).isDisabled(), 'Saved ID is immutable');
  await page.getByRole('textbox', { name: '模型组名称', exact: true }).fill('保存失败仍保留的草稿');
  failSave = true;
  await page.getByRole('button', { name: '保存模型组', exact: true }).click();
  await page.getByText('离线模拟：保存失败，原配置未改变', { exact: true }).waitFor();
  assert(await page.getByRole('textbox', { name: '模型组名称', exact: true }).inputValue() === '保存失败仍保留的草稿', 'Failed writes preserve editor');
  assert(groups[0].name === '编程助手', 'Failed writes retain persisted config');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '继续编辑', exact: true }).click();
  assert(await page.getByRole('textbox', { name: '模型组名称', exact: true }).inputValue() === '保存失败仍保留的草稿', 'Canceling close retains the unsaved draft');
  await modal.locator('.el-dialog__headerbtn').click();
  await page.getByRole('button', { name: '丢弃修改', exact: true }).click();
  await modal.waitFor({ state: 'hidden' });
  assert(groups[0].name === '编程助手', 'Discarding a draft does not mutate the saved configuration');
  await page.locator('.auto-group').getByRole('button', { name: '编辑', exact: true }).click();
  await editor.waitFor();
  failSave = false;
  await page.getByRole('textbox', { name: '模型组名称', exact: true }).fill('编程助手 · 日常备用');
  await page.getByRole('button', { name: '保存模型组', exact: true }).click();
  await modal.waitFor({ state: 'hidden' });
  const patch = writes.find(write => write.method === 'PATCH' && write.body.targets);
  assert(patch && patch.body.targets.every(target => Object.keys(target).sort().join() === 'enabled,model'), 'PATCH strips all target runtime health metadata');
  await page.locator('.auto-group').getByRole('button', { name: '停用', exact: true }).click();
  await page.locator('.auto-group').getByText('已停用', { exact: true }).waitFor();
  await page.locator('.auto-group').getByRole('button', { name: '启用', exact: true }).click();
  await page.locator('.auto-group').getByText('已启用', { exact: true }).waitFor();
  failRead = true;
  await page.getByRole('button', { name: '刷新配置', exact: true }).click();
  await page.getByText('离线模拟：读取失败 当前显示上次成功读取的配置。', { exact: true }).waitFor();
  assert(await page.locator('.auto-group').count() === 1, 'Read errors retain last successful snapshot');
  failRead = false;
  await page.getByRole('button', { name: '刷新配置', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.auto-toolbar .el-button.is-loading'));
  await page.locator('.el-message').first().waitFor({ state: 'hidden' });
  for (const theme of ['default', 'klee']) {
    if (theme === 'klee') await page.getByRole('button', { name: '开启可莉主题', exact: true }).click();
    await page.locator('.auto-group').getByRole('button', { name: '编辑', exact: true }).click();
    await editor.waitFor();
    await modal.locator('.auto-advanced summary').click();
    for (const width of [1440, 1000, 390]) {
      const height = width === 390 ? 844 : width === 1000 ? 550 : 1000;
      await page.setViewportSize({ width, height });
      await modal.getByRole('button', { name: /展开全部.*模型/ }).click();
      await page.evaluate(() => { document.activeElement?.blur(); document.querySelector('.auto-model-dialog .el-dialog__body').scrollTop = 0; });
      await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), theme + ' ' + width + ' no horizontal overflow');
      const bounds = await modal.boundingBox();
      assert(bounds.x >= 0 && bounds.y + bounds.height <= height, 'Dialog must fit the viewport');
      assert(await modal.getByRole('button', { name: '保存模型组', exact: true }).isVisible(), 'Footer remains visible on mobile');
      const scrolling = await modal.evaluate(element => {
        const overlay = element.closest('.el-overlay-dialog');
        const body = element.querySelector('.el-dialog__body');
        const scrollbars = [...element.querySelectorAll('*')].filter(node => /auto|scroll/.test(getComputedStyle(node).overflowY) && node.scrollHeight > node.clientHeight + 1).map(node => node.className);
        return { scrollbars, overlayOverflow: overlay.scrollHeight > overlay.clientHeight + 1, backgroundLocked: getComputedStyle(document.body).overflowY === 'hidden', bodyScrollable: body.scrollHeight > body.clientHeight, scrollbarHidden: getComputedStyle(body).scrollbarWidth === 'none' };
      });
      assert(scrolling.scrollbars.length === 1 && scrolling.scrollbars[0].includes('el-dialog__body'), 'Only dialog body may scroll: ' + scrolling.scrollbars.join(', '));
      assert(!scrolling.overlayOverflow, 'Overlay must not create another scrollbar');
      assert(scrolling.backgroundLocked, 'Background page must stay locked while dialog is open');
      assert(scrolling.bodyScrollable, 'Long catalogs must remain reachable in the main dialog scroll area');
      assert(scrolling.scrollbarHidden, 'Dialog scrollbar must be hidden while retaining scroll interaction');
      await modal.locator('.auto-catalog article').first().scrollIntoViewIfNeeded();
      const beforeWheel = await modal.locator('.el-dialog__body').evaluate(body => body.scrollTop);
      const catalogRow = await modal.locator('.auto-catalog article').first().boundingBox();
      await page.mouse.move(catalogRow.x + catalogRow.width / 2, catalogRow.y + catalogRow.height / 2);
      await page.mouse.wheel(0, 180);
      await page.waitForFunction(previous => document.querySelector('.auto-model-dialog .el-dialog__body').scrollTop > previous, beforeWheel);
      await modal.locator('.el-dialog__body').evaluate(body => { body.scrollTop = body.scrollHeight; });
      await modal.getByText('超时后，上游可能仍在生成。开启超时切换可能产生额外消耗。', { exact: true }).waitFor();
      await modal.getByRole('button', { name: '向下滚动查看更多', exact: true }).waitFor({ state: 'hidden' });
      await modal.getByRole('button', { name: '回到顶部并收起', exact: true }).click();
      await page.waitForFunction(() => document.querySelector('.auto-model-dialog .el-dialog__body').scrollTop === 0);
      assert(await modal.locator('.auto-catalog article').count() === 10, 'Back-to-top action also collapses the catalog');
      await page.screenshot({ path: 'output/playwright/auto-model-modal-' + theme + '-' + width + '.png', animations: 'disabled', caret: 'hide' });
    }
    await modal.locator('.el-dialog__headerbtn').click();
    await modal.waitFor({ state: 'hidden' });
    await page.waitForFunction(() => getComputedStyle(document.body).overflowY !== 'hidden');
    await page.setViewportSize({ width: 1440, height: 1000 });
  }
  await page.locator('.auto-group').getByRole('button', { name: '删除', exact: true }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert(groups.length === 1, 'Canceled deletion preserves group');
  await page.locator('.auto-group').getByRole('button', { name: '删除', exact: true }).click();
  await page.getByRole('button', { name: '确认删除', exact: true }).click();
  await page.getByRole('heading', { name: '先为常用任务建一个组' }).waitFor();
  assert(groups.length === 0 && writes.some(write => write.method === 'DELETE' && write.id === 'auto/coding'), 'Confirmed deletion uses encoded complete ID');
  await page.getByRole('button', { name: '新建模型组', exact: true }).click();
  await dialog.waitFor();
  await modal.getByRole('button', { name: '取消编辑', exact: true }).click();
  await modal.waitFor({ state: 'hidden' });
  warning = '离线模拟：配置文件损坏';
  await page.getByRole('button', { name: '刷新配置', exact: true }).click();
  await page.getByText(warning + ' 为保护原文件，已暂停配置修改。', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: '新建模型组', exact: true }).isDisabled(), 'Damaged configuration is read-only');
  assert(errors.length === 0, 'Browser runtime errors: ' + errors.join('; '));
  return 'PASS: ten-model default, full-catalog search, expand/back-to-top/collapse, preserved selections, hidden scrollbar with working guidance, one scroll area and two themes at 390/1000/1440px.';
}
